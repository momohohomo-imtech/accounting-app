-- 103: 공사 작업 순서표 메모(11/4 사용자 요청 "작업 순서 최상단에 메모 항 — 작업 지시사항·전달사항 등 주요 내용 전달용,
-- 인쇄 때도 프로젝트 이름 아래", 사용자 결정 "SQL 103으로 진행") — work_sequences 표에 memo 칸 하나만 추가.
-- 기존 순서표·단계 자료는 하나도 바꾸지 않음(기존 순서표의 메모는 빈칸). 두 번 실행해도 문제없음.
-- 실행 전엔 앱이 메모 칸을 숨기고 저장하지 않음(나머지는 그대로 동작).
-- 백업·복원은 칸을 따로 고칠 필요 없음: 백업은 표의 칸 전부(*)를 담고, 복원 함수(096)는 표에 있는 칸만 넣음(예전 백업엔 메모가
-- 없어서 빈칸으로 복원됨).

alter table public.work_sequences
  add column if not exists memo text;

-- PostgREST(Supabase API 레이어)가 새 칸을 바로 알도록 스키마를 다시 읽게 함.
notify pgrst, 'reload schema';
